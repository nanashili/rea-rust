#!/bin/sh
# Fetch the pinned frida-core devkit into a local cache and verify its SHA-256.
#
# The `frida` feature of rea-tools-debug links frida-core through
# `frida-sys =0.17.2` without its `auto-download` feature, so cargo never
# touches the network for Frida. This script is the only download step.
#
# Usage: fetch-frida-devkit.sh            (prints the devkit directory)
#        eval "$(fetch-frida-devkit.sh --env)"  (exports build variables)
#
# Pinned version: 17.23.2, the frida-core shipped by the TypeScript oracle's
# `frida` npm package. frida-sys 0.17.2 was published against 17.9.5; its
# bindings are generated by bindgen from this devkit's header at build time.
set -eu

FRIDA_VERSION=17.23.2

os=$(uname -s)
arch=$(uname -m)
case "$os/$arch" in
  Darwin/arm64)
    platform=macos-arm64
    sha256=e9d29bccc67ade46eddfb72bb3ab1cc772cba3b27ddf1b962f8321e13f2ca9c6 ;;
  Darwin/x86_64)
    platform=macos-x86_64
    sha256= ;;
  Linux/x86_64)
    platform=linux-x86_64
    sha256= ;;
  Linux/aarch64)
    platform=linux-arm64
    sha256= ;;
  *)
    echo "fetch-frida-devkit: unsupported host $os/$arch" >&2
    exit 1 ;;
esac
if [ -z "$sha256" ]; then
  echo "fetch-frida-devkit: no pinned SHA-256 for $platform; add one from the release's asset digest before use" >&2
  exit 1
fi

cache_root=${REA_FRIDA_DEVKIT_CACHE:-}
if [ -z "$cache_root" ]; then
  if [ "$os" = Darwin ]; then
    cache_root="$HOME/Library/Caches/dev-build/frida-devkit"
  else
    cache_root="${XDG_CACHE_HOME:-$HOME/.cache}/dev-build/frida-devkit"
  fi
fi
asset="frida-core-devkit-$FRIDA_VERSION-$platform.tar.xz"
directory="$cache_root/$FRIDA_VERSION/$platform"
marker="$directory/.verified-$sha256"

if [ ! -f "$marker" ]; then
  mkdir -p "$cache_root/$FRIDA_VERSION"
  staging=$(mktemp -d "$cache_root/$FRIDA_VERSION/.staging.XXXXXX")
  trap 'rm -rf "$staging"' EXIT INT TERM
  curl --fail --location --silent --show-error \
    --output "$staging/$asset" \
    "https://github.com/frida/frida/releases/download/$FRIDA_VERSION/$asset"
  actual=$(shasum -a 256 "$staging/$asset" | cut -d' ' -f1)
  if [ "$actual" != "$sha256" ]; then
    echo "fetch-frida-devkit: SHA-256 mismatch for $asset: expected $sha256, got $actual" >&2
    exit 1
  fi
  mkdir "$staging/devkit"
  tar -xJf "$staging/$asset" -C "$staging/devkit"
  for required in frida-core.h libfrida-core.a; do
    if [ ! -f "$staging/devkit/$required" ]; then
      echo "fetch-frida-devkit: $asset lacks $required" >&2
      exit 1
    fi
  done
  : > "$staging/devkit/.verified-$sha256"
  rm -rf "$directory"
  mv "$staging/devkit" "$directory"
fi

if [ "${1:-}" = "--env" ]; then
  # bindgen (frida-sys build script) reads the header; rea-tools-debug's
  # build script adds the library search path.
  printf 'export REA_FRIDA_DEVKIT_DIR=%s\n' "'$directory'"
  printf 'export BINDGEN_EXTRA_CLANG_ARGS=%s\n' "'-I$directory'"
else
  printf '%s\n' "$directory"
fi
